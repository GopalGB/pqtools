def explain(name: str) -> str | None:
    """The refusal message for a documented-but-unimplemented function.

    Returns None for a name Microsoft does not document, which keeps a
    genuine typo reading as a typo - the distinction this file exists to
    draw. Do not make this fall back to a generic message.
    """
    reason = DOCUMENTED.get(name)
    if reason is None:
        return None
    return f"{name} {REASONS[reason]}"


