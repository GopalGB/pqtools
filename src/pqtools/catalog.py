"""Every function Microsoft's M reference documents, and why we do or don't run it.

The point of this file is the quality of one error message.

Before it existed, `Salesforce.Data(...)` raised `unknown identifier:
Salesforce.Data` - the same error a typo produces. A reader cannot tell from
that whether they misspelled something, whether pqtools is broken, or whether
the function is real but unimplemented. Meanwhile `SharePoint.Files` got a
proper typed refusal explaining itself, because someone had listed it by hand.

README.md and llms.txt both promise that any construct pqtools cannot evaluate
"raises a typed error naming it". For roughly six hundred documented functions
that promise was not being kept.

So this catalog names every documented function and the reason it is not
implemented. It is consulted ONLY when a name is absent from ``BUILTINS``,
which makes it self-maintaining: implement a function and it stops being
consulted for that name, with nothing to remember to delete. That property is
deliberate - the previous hand-maintained list had already drifted.

Regenerate with ``python scripts/sync_m_catalog.py`` (see that script for the
Microsoft Learn pages it reads). Do not hand-edit the DOCUMENTED table.
"""

